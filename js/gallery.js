/* Misambi Medical Mission - interactive gallery (gallery.html only)
   Data comes from js/gallery-data.js, generated by tools/build_gallery.py. */
(function () {
  "use strict";
  var DATA = window.MISAMBI_GALLERY;
  var root = document.querySelector(".mg");
  if (!DATA || !root || !DATA.photos || !DATA.photos.length) return;

  var PAGE = 36;                      /* photos rendered per "page" */
  var MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
  var DAYS = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
  var reduceMotion = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  var byId = {};
  DATA.photos.forEach(function (p) { byId[p.id] = p; });

  /* ---------- helpers ---------- */
  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }
  function parts(p) {                 /* date parts without timezone shifts */
    if (!p.d) return null;
    var y = +p.d.slice(0, 4), m = +p.d.slice(5, 7) - 1, d = +p.d.slice(8, 10);
    return { y: y, m: m, d: d, dow: new Date(y, m, d).getDay() };
  }
  function dayKey(p) { return p.d ? p.d.slice(0, 10) : "undated"; }
  function monthKey(p) { return p.d ? p.d.slice(0, 7) : "undated"; }
  function fmtDay(p, withDow) {
    var x = parts(p);
    if (!x) return "Date not available";
    return (withDow ? DAYS[x.dow] + ", " : "") + x.d + " " + MONTHS[x.m] + " " + x.y;
  }
  function fmtMonth(p) { var x = parts(p); return x ? MONTHS[x.m] + " " + x.y : "Date not available"; }
  function altFor(p) { return p.c || "Misambi Medical Mission photo, " + fmtDay(p, false); }

  /* ---------- state ---------- */
  var sortDir = "desc";
  var list = [];                      /* photos in current order */
  var rendered = 0;
  var groupsEl = root.querySelector(".mg-groups");
  var timelineEl = root.querySelector(".mg-timeline");
  var progressEl = root.querySelector(".mg-progress");
  var loadBtn = root.querySelector(".mg-load");
  var allEl = root.querySelector(".mg-all");
  var exploreBtn = root.querySelector(".mg-explore");
  var dayEls = {};                    /* dayKey -> grid element */
  var monthEls = {};

  function ordered() {
    var dated = DATA.photos.filter(function (p) { return p.d; });
    var undated = DATA.photos.filter(function (p) { return !p.d; });
    dated.sort(function (a, b) { return sortDir === "desc" ? (a.d < b.d ? 1 : a.d > b.d ? -1 : 0) : (a.d > b.d ? 1 : a.d < b.d ? -1 : 0); });
    return dated.concat(undated);
  }

  /* ---------- totals in the header ---------- */
  root.querySelectorAll("[data-gallery-total]").forEach(function (n) { n.textContent = DATA.photos.length; });

  /* ---------- timeline (jump to date) ---------- */
  function buildTimeline() {
    timelineEl.innerHTML = "";
    var months = [], seen = {};
    list.forEach(function (p) {
      var mk = monthKey(p), dk = dayKey(p);
      if (!seen[mk]) { seen[mk] = { label: fmtMonth(p), days: [], dayIdx: {} }; months.push(seen[mk]); }
      var m = seen[mk];
      if (m.dayIdx[dk] == null) { m.dayIdx[dk] = m.days.length; m.days.push({ key: dk, p: p, n: 0 }); }
      m.days[m.dayIdx[dk]].n++;
    });
    months.forEach(function (m) {
      var wrap = el("div", "mg-tl-month");
      wrap.appendChild(el("span", "mg-tl-label", m.label));
      m.days.forEach(function (d) {
        var b = el("button", "mg-tl-day");
        b.type = "button";
        b.setAttribute("data-day", d.key);
        var x = parts(d.p);
        b.innerHTML = "";
        b.appendChild(el("strong", null, x ? String(x.d) : "?"));
        b.appendChild(el("span", null, x ? MONTHS[x.m].slice(0, 3) : "No date"));
        b.appendChild(el("em", null, d.n));
        b.setAttribute("aria-label", fmtDay(d.p, true) + ", " + d.n + " photos");
        b.addEventListener("click", function () { jumpTo(d.key); });
        wrap.appendChild(b);
      });
      timelineEl.appendChild(wrap);
    });
  }

  /* ---------- rendering ---------- */
  function ensureGroup(p) {
    var mk = monthKey(p), dk = dayKey(p);
    if (!monthEls[mk]) {
      var ms = el("section", "mg-month");
      var count = list.filter(function (q) { return monthKey(q) === mk; }).length;
      var h = el("h2", "mg-month-title", fmtMonth(p));
      h.appendChild(el("span", "mg-count", count + (count === 1 ? " photo" : " photos")));
      ms.appendChild(h);
      groupsEl.appendChild(ms);
      monthEls[mk] = ms;
    }
    if (!dayEls[dk]) {
      var ds = el("div", "mg-day");
      ds.id = "mg-day-" + dk;
      var n = list.filter(function (q) { return dayKey(q) === dk; }).length;
      var head = el("div", "mg-day-head");
      var h3 = el("h3", "mg-day-title");
      var t = el("time", null, fmtDay(p, true));
      if (p.d) t.setAttribute("datetime", dk);
      h3.appendChild(t);
      head.appendChild(h3);
      var title = DATA.collections && DATA.collections[dk];
      if (title) head.appendChild(el("p", "mg-day-sub", title));
      head.appendChild(el("span", "mg-count", n + (n === 1 ? " photo" : " photos")));
      ds.appendChild(head);
      var grid = el("div", "mg-grid");
      ds.appendChild(grid);
      monthEls[mk].appendChild(ds);
      dayEls[dk] = grid;
    }
    return dayEls[dk];
  }

  function tile(p, index) {
    var b = el("button", "mg-item" + (p.h > p.w ? " is-tall" : ""));
    b.type = "button";
    b.style.setProperty("--bg", p.bg || "#dfe9d6");
    b.setAttribute("data-index", index);
    b.setAttribute("aria-label", "Open photo: " + altFor(p));
    var img = new Image();
    img.alt = "";
    img.loading = "lazy";
    img.decoding = "async";
    img.width = p.tw; img.height = p.th;
    img.addEventListener("load", function () { b.classList.add("is-loaded"); });
    img.addEventListener("error", function () { b.classList.add("is-broken"); });
    img.src = p.t;
    b.appendChild(img);
    if (p.c) b.appendChild(el("span", "mg-item-cap", p.c));
    b.addEventListener("click", function () { openViewer(index, b); });
    return b;
  }

  function renderMore(upTo) {
    var target = Math.min(list.length, upTo != null ? upTo : rendered + PAGE);
    for (var i = rendered; i < target; i++) {
      var p = list[i];
      var grid = ensureGroup(p);
      grid.appendChild(tile(p, i));
    }
    rendered = target;
    progressEl.textContent = "Showing " + rendered + " of " + list.length + " photos";
    loadBtn.hidden = rendered >= list.length;
    if (rendered >= list.length) progressEl.textContent = "You've seen all " + list.length + " photos";
  }

  function resetRender() {
    list = ordered();
    groupsEl.innerHTML = "";
    dayEls = {}; monthEls = {}; rendered = 0;
    buildTimeline();
    renderMore();
  }

  function jumpTo(dk) {
    var last = -1;
    list.forEach(function (p, i) { if (dayKey(p) === dk && last < 0) last = i; });
    if (last < 0) return;
    if (last >= rendered) renderMore(Math.min(list.length, last + PAGE));
    var target = document.getElementById("mg-day-" + dk);
    if (target) target.scrollIntoView({ behavior: reduceMotion ? "auto" : "smooth", block: "start" });
  }

  /* infinite scroll (the button stays as a fallback) */
  var sentinel = root.querySelector(".mg-sentinel");
  if ("IntersectionObserver" in window && sentinel) {
    var sio = new IntersectionObserver(function (entries) {
      if (entries[0].isIntersecting && !allEl.hidden && rendered < list.length) {
        renderMore();
        /* re-observe so the check runs again if the end is still in view */
        sio.unobserve(sentinel);
        requestAnimationFrame(function () { sio.observe(sentinel); });
      }
    }, { rootMargin: "600px 0px" });
    sio.observe(sentinel);
  }
  loadBtn.addEventListener("click", function () { renderMore(); });

  root.querySelectorAll(".mg-sort button").forEach(function (b) {
    b.addEventListener("click", function () {
      if (b.getAttribute("data-sort") === sortDir) return;
      sortDir = b.getAttribute("data-sort");
      root.querySelectorAll(".mg-sort button").forEach(function (x) { x.setAttribute("aria-pressed", x === b ? "true" : "false"); });
      resetRender();
    });
  });

  function explore(scroll) {
    if (allEl.hidden) {
      allEl.hidden = false;
      resetRender();
      exploreBtn.setAttribute("aria-expanded", "true");
      exploreBtn.querySelector(".mg-explore-label").textContent = "Showing all " + DATA.photos.length + " photos";
      exploreBtn.classList.add("is-open");
    }
    if (scroll) allEl.scrollIntoView({ behavior: reduceMotion ? "auto" : "smooth", block: "start" });
  }
  exploreBtn.addEventListener("click", function () { explore(true); });

  /* featured tiles: open in the viewer instead of following the link */
  root.querySelectorAll(".mg-feature").forEach(function (a) {
    var img = a.querySelector("img");
    if (img.complete) a.classList.add("is-loaded");
    else img.addEventListener("load", function () { a.classList.add("is-loaded"); });
    a.addEventListener("click", function (e) {
      if (e.ctrlKey || e.metaKey || e.shiftKey) return;
      e.preventDefault();
      if (!list.length) list = ordered();
      var idx = -1;
      list.forEach(function (p, i) { if (p.id === a.getAttribute("data-id")) idx = i; });
      if (idx >= 0) openViewer(idx, a);
    });
  });

  /* ---------- viewer ---------- */
  var lb = document.querySelector(".mg-lb");
  var lbImg = lb.querySelector(".mg-lb-img");
  var lbStage = lb.querySelector(".mg-lb-stage");
  var lbDate = lb.querySelector(".mg-lb-date");
  var lbCap = lb.querySelector(".mg-lb-cap");
  var lbCount = lb.querySelector(".mg-lb-count");
  var cur = 0, lastFocus = null, token = 0;
  var preloaded = {};

  /* size the image to fit the stage while keeping its aspect ratio */
  function fit() {
    var p = list[cur];
    if (!p || lb.hidden) return;
    var cs = getComputedStyle(lbStage);
    var bw = lbStage.clientWidth - parseFloat(cs.paddingLeft) - parseFloat(cs.paddingRight);
    var bh = lbStage.clientHeight - parseFloat(cs.paddingTop) - parseFloat(cs.paddingBottom);
    var s = Math.min(bw / p.w, bh / p.h, 1.5);
    lbImg.style.width = Math.round(p.w * s) + "px";
    lbImg.style.height = Math.round(p.h * s) + "px";
  }
  window.addEventListener("resize", fit);

  function preload(i) {
    var p = list[(i + list.length) % list.length];
    if (p && !preloaded[p.f]) { var im = new Image(); im.src = p.f; preloaded[p.f] = im; }
  }

  function show(i, dir) {
    cur = (i + list.length) % list.length;
    var p = list[cur];
    var my = ++token;
    lb.classList.add("is-loading");
    lbStage.classList.remove("slide-left", "slide-right");
    lbImg.style.backgroundImage = "url('" + p.t + "')";   /* thumbnail shows instantly, full image replaces it */
    lbImg.removeAttribute("src");
    fit();
    var full = new Image();
    full.onload = function () {
      if (my !== token) return;
      lbImg.src = p.f;
      lb.classList.remove("is-loading");
    };
    full.onerror = function () { if (my === token) { lbImg.src = p.t; lb.classList.remove("is-loading"); } };
    full.src = p.f;
    lbImg.alt = altFor(p);
    lbDate.textContent = fmtDay(p, true) + (p.ds === "file" ? " (approximate)" : "");
    if (p.d) lbDate.setAttribute("datetime", p.d.slice(0, 10)); else lbDate.removeAttribute("datetime");
    lbCap.textContent = p.c || (DATA.collections && DATA.collections[dayKey(p)]) || "";
    lbCount.textContent = (cur + 1) + " / " + list.length;
    if (dir && !reduceMotion) { void lbStage.offsetWidth; lbStage.classList.add(dir > 0 ? "slide-left" : "slide-right"); }
    preload(cur + 1); preload(cur - 1);
    try { history.replaceState(null, "", "#photo=" + p.id); } catch (e) {}
  }

  function openViewer(i, from) {
    lastFocus = from || document.activeElement;
    lb.hidden = false;
    document.documentElement.classList.add("mg-lock");
    show(i, 0);
    requestAnimationFrame(function () { lb.classList.add("open"); });
    lb.querySelector(".mg-lb-close").focus();
  }
  function closeViewer() {
    lb.classList.remove("open");
    document.documentElement.classList.remove("mg-lock");
    setTimeout(function () { lb.hidden = true; lbImg.removeAttribute("src"); }, reduceMotion ? 0 : 200);
    try { history.replaceState(null, "", location.pathname + location.search); } catch (e) {}
    if (lastFocus && document.body.contains(lastFocus)) lastFocus.focus();
  }
  function next() { show(cur + 1, 1); }
  function prev() { show(cur - 1, -1); }

  lb.querySelector(".mg-lb-close").addEventListener("click", closeViewer);
  lb.querySelector(".mg-lb-next").addEventListener("click", next);
  lb.querySelector(".mg-lb-prev").addEventListener("click", prev);
  lb.addEventListener("click", function (e) {
    if (e.target === lb || e.target === lbStage) closeViewer();
  });
  document.addEventListener("keydown", function (e) {
    if (lb.hidden) return;
    if (e.key === "Escape") { e.preventDefault(); closeViewer(); }
    else if (e.key === "ArrowRight") { e.preventDefault(); next(); }
    else if (e.key === "ArrowLeft") { e.preventDefault(); prev(); }
    else if (e.key === "Tab") {                 /* keep focus inside the viewer */
      var f = lb.querySelectorAll("button");
      var first = f[0], last = f[f.length - 1];
      if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
    }
  });

  /* swipe on touch screens */
  var sx = 0, sy = 0, tracking = false;
  lb.addEventListener("touchstart", function (e) {
    if (e.touches.length !== 1) return;
    tracking = true; sx = e.touches[0].clientX; sy = e.touches[0].clientY;
  }, { passive: true });
  lb.addEventListener("touchend", function (e) {
    if (!tracking) return;
    tracking = false;
    var dx = e.changedTouches[0].clientX - sx, dy = e.changedTouches[0].clientY - sy;
    if (Math.abs(dx) > 50 && Math.abs(dx) > Math.abs(dy) * 1.3) { dx < 0 ? next() : prev(); }
    else if (dy > 90 && Math.abs(dy) > Math.abs(dx) * 1.5) closeViewer();   /* swipe down to close */
  }, { passive: true });

  /* open a shared link like gallery.html#photo=2026-11-07-di0a2088 */
  var m = location.hash.match(/^#photo=([\w-]+)/);
  if (m && byId[m[1]]) {
    list = ordered();
    for (var k = 0; k < list.length; k++) if (list[k].id === m[1]) { openViewer(k); break; }
  }
})();
